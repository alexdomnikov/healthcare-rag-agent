import json
import sys
from pathlib import Path

from dotenv import load_dotenv

import retrieval_mode as abl1
import reranker as abl2
import chunking_strategy as abl3

load_dotenv()

# Runs all three ablations and writes docs/ablations.md
# Prerequisite for ablation 3: uv run scripts/ingest_fixed_chunks.py
# Run everything and rebuild docs: uv run eval/ablations/run_all.py

ROOT = Path(__file__).resolve().parents[2]
GT_PATH = ROOT / "eval" / "ground_truth.json"
ABL_DIR = ROOT / "eval" / "ablations"
DOCS_DIR = ROOT / "docs"
MD_PATH = DOCS_DIR / "ablations.md"

def load_ground_truth() -> list[dict]:
    if not GT_PATH.exists():
        print(f"ERROR: {GT_PATH} not found")
        sys.exit(1)
    with open(GT_PATH) as f:
        return json.load(f)

def run_all(ground_truth: list[dict]) -> tuple[dict, dict, dict]:
    print("ABLATION 1: retrieval mode")
    print("*" * 60)
    r1 = abl1.run_ablation(ground_truth)

    print()
    print("ABLATION 2: reranker")
    print("*" * 60)
    r2 = abl2.run_ablation(ground_truth)

    print()
    print("ABLATION 3: chunking strategy")
    print("*" * 60)
    r3 = abl3.run_ablation(ground_truth)

    return r1, r2, r3

def production_config_md(r1: dict, r2: dict, r3: dict) -> str:
    best_mode = max(
        abl1.MODES,
        key=lambda m: r1[m]["aggregates"]["recall@5"],
    )
    reranker_helps = r2["on"]["aggregates"]["recall@5"] >= r2["off"]["aggregates"]["recall@5"]
    chunking_wins = r3["structure"]["aggregates"]["recall@5"] >= r3["fixed"]["aggregates"]["recall@5"]

    return f"""\
## Production config

Based on all three ablations, the locked-in defaults are:

| Setting | Value | Rationale |
|---------|-------|-----------|
| Retrieval mode | `{best_mode}` | Highest Recall@5 in Ablation 1 |
| Reranker | `{"on" if reranker_helps else "off"}` | {"Improves" if reranker_helps else "Neutral"} Recall@5 in Ablation 2 |
| Chunking strategy | `{"structure-aware" if chunking_wins else "fixed-size"}` | {"Wins" if chunking_wins else "Wins"} in Ablation 3 |

These defaults are encoded in `src/healthcare_rag/config.py`.
"""


def build_md(r1: dict, r2: dict, r3: dict) -> None:
    DOCS_DIR.mkdir(parents=True, exist_ok=True)

    content = (
        "# Ablation Studies\n\n"
        "All ablations use the 18 vector-search document questions in "
        "`eval/ground_truth.json`. Generated by `eval/ablations/run_all.py`. "
        "Do not edit by hand.\n\n"
        "---\n\n"
        + abl1.section_md(r1)
        + "\n---\n\n"
        + abl2.section_md(r2)
        + "\n---\n\n"
        + abl3.section_md(r3)
        + "\n---\n\n"
        + production_config_md(r1, r2, r3)
    )

    MD_PATH.write_text(content)
    print(f"docs/ablations.md written ({len(content)} chars)")


def main() -> None:
    ABL_DIR.mkdir(parents=True, exist_ok=True)

    gt = load_ground_truth()
    r1, r2, r3 = run_all(gt)
    build_md(r1, r2, r3)
    print(f"\nDone. View: {MD_PATH}")


if __name__ == "__main__":
    main()