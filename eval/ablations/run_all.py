import json
import sys
from pathlib import Path

from dotenv import load_dotenv

import retrieval_mode as abl1
import reranker as abl2
import chunking_strategy as abl3

load_dotenv()

# Runs all three ablations and rewrites docs/ablations.md.
#   uv run eval/ablations/run_all.py
# Prereq for ablation 3: uv run scripts/ingest.py --strategy fixed

ROOT = Path(__file__).resolve().parents[2]
GT_PATH = ROOT / "eval" / "ground_truth.json"
ABL_DIR = ROOT / "eval" / "ablations"
DOCS_DIR = ROOT / "docs"
MD_PATH = DOCS_DIR / "ablations.md"


def load_ground_truth() -> list[dict]:
    if not GT_PATH.exists():
        print(f"ERROR: {GT_PATH} not found")
        sys.exit(1)
    with open(GT_PATH) as f:
        return json.load(f)

def run_all(ground_truth: list[dict]) -> tuple[dict, dict, dict]:
    print("\n[Ablation 1] retrieval mode")
    r1 = abl1.run_ablation(ground_truth)

    print("\n[Ablation 2] reranker")
    r2 = abl2.run_ablation(ground_truth)

    print("\n[Ablation 3] chunking strategy")
    r3 = abl3.run_ablation(ground_truth)

    return r1, r2, r3

def production_config_md(r1: dict, r2: dict, r3: dict) -> str:
    best_mode = max(
        abl1.MODES,
        key=lambda m: r1[m]["aggregates"]["recall@5"],
    )
    reranker_helps = r2["on"]["aggregates"]["recall@5"] >= r2["off"]["aggregates"]["recall@5"]
    chunking_wins = r3["structure"]["aggregates"]["recall@5"] >= r3["fixed"]["aggregates"]["recall@5"]

    # Chunker is a judgement call, not a pure-numbers pick. Even when fixed-size
    # wins raw Recall, structure-aware carries section_path metadata that
    # produces cleaner citations. The table always shows the shipped config
    # (hybrid_chunker); the rationale column explains why on each run.
    chunker_rationale = (
        "Wins in Ablation 3 on Recall@5."
        if chunking_wins
        else "Fixed-size wins Ablation 3 on raw Recall@5, but structure-aware "
        "carries section_path metadata for cleaner citations. The recall "
        "trade is small, and the citation-precision lift in "
        "`docs/eval_final.md` validates it."
    )
    return f"""\
## Production config

Based on all three ablations, the locked-in defaults are:

| Setting | Value | Rationale |
|---------|-------|-----------|
| Retrieval mode | `{best_mode}` | Highest Recall@5 in Ablation 1. |
| Reranker | `{"on" if reranker_helps else "off"}` | {"Improves" if reranker_helps else "Neutral"} Recall@5 in Ablation 2. |
| Chunking strategy | `hybrid_chunker` (structure-aware) | {chunker_rationale} |

Defaults live in `src/healthcare_rag/retrieval.py` (`DEFAULT_STRATEGY`) and
the agent system prompt in `src/healthcare_rag/core.py`.
"""


def build_md(r1: dict, r2: dict, r3: dict) -> None:
    DOCS_DIR.mkdir(parents=True, exist_ok=True)

    content = (
        "# Ablation Studies\n\n"
        "All ablations use the 18 vector-search document questions in "
        "`eval/ground_truth.json`. Generated by `eval/ablations/run_all.py`. "
        "Do not edit by hand.\n\n"
        "---\n\n"
        + abl1.section_md(r1)
        + "\n---\n\n"
        + abl2.section_md(r2)
        + "\n---\n\n"
        + abl3.section_md(r3)
        + "\n---\n\n"
        + production_config_md(r1, r2, r3)
    )

    MD_PATH.write_text(content)
    print(f"docs/ablations.md written ({len(content)} chars)")


def main() -> None:
    ABL_DIR.mkdir(parents=True, exist_ok=True)

    gt = load_ground_truth()
    r1, r2, r3 = run_all(gt)
    build_md(r1, r2, r3)
    print(f"\nDone. View: {MD_PATH}")


if __name__ == "__main__":
    main()